class TelemetryHubHandler(BaseHTTPRequestHandler):

    def _set_cors_headers(self, content_type="application/json"):
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Content-Type, Authorization")
        self.send_header("Content-Type", content_type)

    def do_OPTIONS(self):
        self.send_response(200)
        self._set_cors_headers()
        self.end_headers()

    def do_GET(self):
        parsed_url = urlparse(self.path)
        path = parsed_url.path

        # 1. Health check & Summary
        if path == "/" or path == "/api/status":
            self.send_response(200)
            self._set_cors_headers("application/json")
            self.end_headers()
            with ALERTS_LOCK:
                active_count = sum(1 for a in ACTIVE_ALERTS if a["status"] != "RESUELTO")
                critical_count = sum(1 for a in ACTIVE_ALERTS if a["status"] != "RESUELTO" and a["severity"] == "CRITICO_ROJO")
            payload = {
                "service": "TinyCardio Rural Triage & SMS Telemetry Hub",
                "version": "1.0.0",
                "status": "ONLINE",
                "active_alerts_count": active_count,
                "critical_alerts_count": critical_count,
                "registered_patients": len(MOCK_PATIENTS),
                "sms_gateway_ready": True
            }
            self.wfile.write(json.dumps(payload, indent=2).encode('utf-8'))

        # 2. Get Active Alerts List
        elif path == "/api/alerts" or path == "/api/alerts/active":
            self.send_response(200)
            self._set_cors_headers("application/json")
            self.end_headers()
            with ALERTS_LOCK:
                now = time.time()
                for alert in ACTIVE_ALERTS:
                    elapsed = now - alert["created_at_epoch"]
                    alert["golden_hour_seconds_left"] = max(0, int(3600 - elapsed))
                data = list(ACTIVE_ALERTS)
            self.wfile.write(json.dumps({"success": True, "count": len(data), "alerts": data}, indent=2).encode('utf-8'))

        # 3. Get Pre-registered Patients Catalog
        elif path == "/api/patients":
            self.send_response(200)
            self._set_cors_headers("application/json")
            self.end_headers()
            self.wfile.write(json.dumps({"success": True, "patients": list(MOCK_PATIENTS.values())}, indent=2).encode('utf-8'))

        # 4. Get Dispatch Vehicles and Resources
        elif path == "/api/resources":
            self.send_response(200)
            self._set_cors_headers("application/json")
            self.end_headers()
            self.wfile.write(json.dumps({"success": True, "resources": DISPATCH_RESOURCES}, indent=2).encode('utf-8'))

        # 5. Real-Time Server-Sent Events (SSE) Stream
        elif path == "/api/alerts/stream":
            self.send_response(200)
            self.send_header("Access-Control-Allow-Origin", "*")
            self.send_header("Content-Type", "text/event-stream")
            self.send_header("Cache-Control", "no-cache")
            self.send_header("Connection", "keep-alive")
            self.end_headers()

            q = []
            with ALERTS_LOCK:
                EVENT_LISTENERS.append(self.wfile)

            try:
                # Send initial snapshot
                with ALERTS_LOCK:
                    snapshot = json.dumps({"type": "SNAPSHOT", "alerts": ACTIVE_ALERTS})
                self.wfile.write(f"data: {snapshot}\n\n".encode('utf-8'))
                self.wfile.flush()

                # Keep connection alive with heartbeat
                while True:
                    time.sleep(15)
                    self.wfile.write(b": keepalive\n\n")
                    self.wfile.flush()
            except (BrokenPipeError, ConnectionResetError):
                with ALERTS_LOCK:
                    if self.wfile in EVENT_LISTENERS:
                        EVENT_LISTENERS.remove(self.wfile)

        else:
            self.send_response(404)
            self._set_cors_headers()
            self.end_headers()
            self.wfile.write(json.dumps({"error": "Endpoint not found"}).encode('utf-8'))

    def do_POST(self):
        parsed_url = urlparse(self.path)
        path = parsed_url.path

        content_length = int(self.headers.get('Content-Length', 0))
        post_body = self.rfile.read(content_length).decode('utf-8')

        # 1. Incoming SMS Telemetry Endpoint
        if path == "/api/sms/incoming" or path == "/api/alerts/incoming":
            # Could be plain text or JSON
            raw_text = post_body
            if "raw_sms" in post_body or "{" in post_body:
                try:
                    js = json.loads(post_body)
                    raw_text = js.get("raw_sms") or js.get("text") or post_body
                except Exception:
                    pass

            parsed_sms = parse_sms_telemetry(raw_text)
            new_alert = create_alert_record(parsed_sms)

            with ALERTS_LOCK:
                # Prepend to active alerts
                ACTIVE_ALERTS.insert(0, new_alert)

                # Broadcast to SSE listeners
                dead_listeners = []
                msg = f"data: {json.dumps({'type': 'NEW_ALERT', 'alert': new_alert})}\n\n".encode('utf-8')
                for client in EVENT_LISTENERS:
                    try:
                        client.write(msg)
                        client.flush()
                    except Exception:
                        dead_listeners.append(client)
                for dl in dead_listeners:
                    if dl in EVENT_LISTENERS:
                        EVENT_LISTENERS.remove(dl)

            self.send_response(201)
            self._set_cors_headers()
            self.end_headers()
            self.wfile.write(json.dumps({
                "success": True,
                "message": "2G SMS Alert processed and queued for clinical dispatch",
                "alert": new_alert
            }, indent=2).encode('utf-8'))

        # 2. Dispatch Ambulance / Resource Endpoint
        elif path == "/api/dispatch/confirm" or path == "/api/dispatch/ambulance":
            try:
                data = json.loads(post_body)
            except Exception:
                data = {}

            alert_id = data.get("alert_id")
            resource_id = data.get("resource_id", "AMB-01")
            operator_notes = data.get("notes", "Despacho inmediato confirmado desde el centro de salud.")

            matched_alert = None
            with ALERTS_LOCK:
                for alert in ACTIVE_ALERTS:
                    if alert["alert_id"] == alert_id:
                        matched_alert = alert
                        break

            if not matched_alert:
                self.send_response(404)
                self._set_cors_headers()
                self.end_headers()
                self.wfile.write(json.dumps({"success": False, "error": "Alert ID not found"}).encode('utf-8'))
                return

            # Find resource
            resource = next((r for r in DISPATCH_RESOURCES if r["id"] == resource_id), DISPATCH_RESOURCES[0])

            # Update alert state
            matched_alert["status"] = "EN_CAMINO"
            matched_alert["dispatch_info"] = {
                "dispatched_at_iso": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                "resource_id": resource["id"],
                "resource_name": resource["type"],
                "estimated_arrival_minutes": 12,
                "operator_notes": operator_notes,
                "return_sms_sent": {
                    "destination_number": matched_alert["patient"].get("emergency_contact", ""),
                    "sms_content": f"TinyCardio: Auxilio despachado. {resource['type']} en camino a su ubicacion. ETA: 12 min. Mantengase recostado."
                }
            }

            # Broadcast update via SSE
            with ALERTS_LOCK:
                msg = f"data: {json.dumps({'type': 'DISPATCH_UPDATE', 'alert': matched_alert})}\n\n".encode('utf-8')
                for client in EVENT_LISTENERS:
                    try:
                        client.write(msg)
                        client.flush()
                    except Exception:
                        pass

            self.send_response(200)
            self._set_cors_headers()
            self.end_headers()
            self.wfile.write(json.dumps({
                "success": True,
                "message": "Resource dispatched successfully and return reassurance SMS queued",
                "alert": matched_alert
            }, indent=2).encode('utf-8'))

        else:
            self.send_response(404)
            self._set_cors_headers()
            self.end_headers()
            self.wfile.write(json.dumps({"error": "Unknown POST endpoint"}).encode('utf-8'))


