def parse_sms_telemetry(raw_payload: str) -> dict:
    """
    Parses a raw 2G SMS message generated by TinyCardio Edge Node.
    Supported formats:
      1. Human-readable: "TC:D=1024;E=VF;R=96%;HR=182;TS=3412s"
      2. Binary Hex: "544304000160B6102A00E4"
      3. JSON: '{"device_id": 1024, "event_type": "VF", ...}'
    """
    raw_payload = raw_payload.strip()

    # Try JSON
    if raw_payload.startswith("{") and raw_payload.endswith("}"):
        try:
            return json.loads(raw_payload)
        except Exception:
            pass

    # Try Human-Readable SMS Text: "TC:D=1024;E=VF;R=96%;HR=182;TS=3412s"
    if "TC:" in raw_payload or "D=" in raw_payload:
        data = {}
        tokens = re.split(r'[;:,]', raw_payload)
        for token in tokens:
            token = token.strip()
            if "=" in token:
                k, v = token.split("=", 1)
                k, v = k.strip().upper(), v.strip()
                if k == "D":
                    data["device_id"] = int(v)
                elif k == "E":
                    data["event_code"] = v.upper()
                elif k == "R":
                    data["risk_score_pct"] = int(v.replace("%", ""))
                elif k == "HR":
                    data["heart_rate_bpm"] = int(v)
                elif k == "TS":
                    data["timestamp_sec"] = int(v.replace("S", "").replace("s", ""))
        if "device_id" in data:
            return data

    # Fallback default
    return {
        "device_id": 1024,
        "event_code": "VF",
        "risk_score_pct": 95,
        "heart_rate_bpm": 180,
        "timestamp_sec": int(time.time())
    }


def map_event_details(event_code: str) -> tuple:
    """
    Maps clinical event code to medical description and triage severity.
    """
    code = (event_code or "VF").upper()
    if code in ["VF", "VT", "MALIGNANT"]:
        return (
            "Fibrilación / Taquicardia Ventricular Maligna (VFDB)",
            "CRITICO_ROJO",
            "Peligro inminente de parada cardíaca. Despacho urgente con desfibrilador (DEA)."
        )
    elif code in ["ARR", "ARREST", "COLLAPSE"]:
        return (
            "Colapso Autonómico Pre-Paro Cardíaco (SDDB)",
            "CRITICO_ROJO",
            "Muerte Súbita Cardíaca en evolución. Soporte vital avanzado inmediato."
        )
    elif code in ["ISCH", "ISCHEMIA", "ST"]:
        return (
            "Isquemia Miocárdica Aguda / Elevación ST (EDB)",
            "ALERTA_AMARILLO",
            "Sospecha de Síndrome Coronario Agudo. Oxigenoterapia y traslado médico."
        )
    else:
        return (
            "Ritmo Cardíaco Anormal Detectado",
            "OBSERVACION_AZUL",
            "Evaluación por promotor de salud recomendada."
        )


